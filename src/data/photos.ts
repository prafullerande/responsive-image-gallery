export type Category = "Terrain" | "Structures" | "Portraits" | "Shadowplay";

export interface Photo {
  id: number;
  num: string;
  title: string;
  category: Category;
  location: string;
  year: string;
  credit: string;
  src: string;
  w: number;
  h: number;
}

const px = (id: number) =>
  `https://images.pexels.com/photos/${id}/pexels-photo-${id}.jpeg`;

/** Grid image — balanced quality/size */
export const gridUrl = (p: Photo) =>
  `${p.src}?auto=compress&cs=tinysrgb&w=900`;

/** Full lightbox image */
export const fullUrl = (p: Photo) =>
  `${p.src}?auto=compress&cs=tinysrgb&w=1800`;

/** Small square thumbnail for the lightbox film strip */
export const thumbUrl = (p: Photo) =>
  `${p.src}?auto=compress&cs=tinysrgb&fit=crop&w=160&h=160`;

